// ormImportPrefixes are the import paths of ORMs, and of the SQLite driver fork one came
// with. Nothing imports them.
func ormImportPrefixes() []string {
	return []string{"gorm.io/", "github.com/jinzhu/gorm", "github.com/glebarez/"}
}

// driverImportPrefixes are the import paths of SQLite drivers. Only the store, which opens
// the database, imports one; everything else reaches the database through it.
func driverImportPrefixes() []string {
	return []string{"modernc.org/sqlite", "github.com/mattn/go-sqlite3", "github.com/ncruces/go-sqlite3"}
}

// sqlCallNames are the methods that run SQL: database/sql's (BeginTx included, since
// transactions go through the store's helper), and an ORM's Raw and Exec.
func sqlCallNames() []string {
	return []string{"ExecContext", "QueryContext", "QueryRowContext", "PrepareContext", "BeginTx", "Raw", "Exec"}
}

// sqlStatement matches a string that reads as an SQL statement, in any case: a keyword
// that starts a statement, followed by what that statement takes next. Prose that only
// starts with one of the words, such as "create the directory" or "update available",
// does not match.
var sqlStatement = regexp.MustCompile(`(?is)^\s*(?:` +
	`select\s+(?:distinct\s+)?[\w.*()%]+(?:\s+as\s+\w+)?\s*(?:,|from\s|;?\s*$)|` +
	`(?:insert|replace)\s+(?:or\s+\w+\s+)?into\s|` +
	`update\s+(?:or\s+\w+\s+)?[\w."]+\s+set\s|` +
	`delete\s+from\s|` +
	`(?:create|drop)\s+(?:(?:temp|temporary|unique|virtual)\s+)?(?:table|index|view|trigger)\s|` +
	`alter\s+table\s|` +
	`pragma\s+[\w.]+\s*(?:=|\(|;|$)|` +
	`begin(?:\s+(?:deferred|immediate|exclusive))?(?:\s+transaction)?\s*;?\s*$|` +
	`savepoint\s+\w+\s*;?\s*$|release\s+savepoint\s|rollback(?:\s+transaction)?\s+to\s|` +
	`with\s+(?:recursive\s+)?\w+(?:\s*\([^)]*\))?\s+as\s*(?:(?:not\s+)?materialized\s*)?\(|` +
	`vacuum(?:\s+into\s|\s*;?\s*$)` +
	`)`)

// sqlCommentOrString matches a comment or a string literal in SQL. The alternatives are
// tried together from left to right, so a quote inside a comment, or two dashes inside a
// string, never starts the other.
var sqlCommentOrString = regexp.MustCompile(`--[^\n]*|/\*(?s:.*?)\*/|'(?:[^']|'')*'`)

// sqlParameter matches a query parameter: a named one, or the argument of sqlc's arg,
// narg, and slice macros, whose names are not tables.
var sqlParameter = regexp.MustCompile(`sqlc\.(?:arg|narg|slice)\s*\(\s*\w*\s*\)|[@:$]\w+`)

// sqlIdentifier matches an SQL identifier, bare or quoted.
var sqlIdentifier = regexp.MustCompile(`"([^"]+)"|\x60([^\x60]+)\x60|\[([^\]]+)\]|([A-Za-z_][A-Za-z0-9_$]*)`)

// tableChange matches a statement that creates, drops, or renames a table, capturing the
// created name (1), the dropped name (2), or a rename's old and new names (3 and 4). Each
// name may be quoted.
var tableChange = regexp.MustCompile(`(?i)` +
	`\bCREATE\s+(?:TEMP(?:ORARY)?\s+)?(?:VIRTUAL\s+)?TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?["\x60\[]?(\w+)|` +
	`\bDROP\s+TABLE\s+(?:IF\s+EXISTS\s+)?["\x60\[]?(\w+)|` +
	`\bALTER\s+TABLE\s+["\x60\[]?(\w+)["\x60\]]?\s+RENAME\s+TO\s+["\x60\[]?(\w+)`)

// schemaChange matches a statement that creates, drops, or alters a table, an index, a
// view, or a trigger, capturing the name it creates or changes, which may be quoted.
var schemaChange = regexp.MustCompile(`(?i)\b(?:create|drop|alter)\s+` +
	`(?:(?:temp|temporary|unique|virtual)\s+)?(?:table|index|view|trigger)\s+` +
	`(?:if\s+(?:not\s+)?exists\s+)?["\x60\[]?(\w+)`)

// sqlcVersionLine matches the version line sqlc writes under its header.
var sqlcVersionLine = regexp.MustCompile(`(?m)^//\s+sqlc (v\S+)$`)

// inStore reports whether the repository path rel is in the store or below it.
func inStore(rel string) bool {
	return rel == storeDir || strings.HasPrefix(rel, storeDir+"/")
}

// hasPrefix reports whether s starts with any of prefixes.
func hasPrefix(s string, prefixes []string) bool {
	return slices.ContainsFunc(prefixes, func(prefix string) bool { return strings.HasPrefix(s, prefix) })
}

func TestNoORM(t *testing.T) {
	t.Parallel()

	var orms, drivers []string

	// Every Go file is parsed whatever its build tags, tests included, so neither a tag
	// nor a test can hide an import from this check.
	for _, rel := range goFiles(t) {
		for _, imp := range fileImports(t, rel) {
			switch {
			case hasPrefix(imp, ormImportPrefixes()):
				orms = append(orms, rel+": "+imp)
			case hasPrefix(imp, driverImportPrefixes()) && !inStore(path.Dir(rel)):
				drivers = append(drivers, rel+": "+imp)
			}
		}
	}

	assert.Empty(t, orms, "the data layer is database/sql with queries sqlc generates; no ORM")
	assert.Empty(t, drivers, "only internal/store opens the database, so only it imports the SQLite driver")
}

// sqlExempt reports whether the Go file rel may hold SQL: a test, or the test support only
// tests import, the database plumbing under internal/store, or an owner's generated query
// package.
func sqlExempt(rel string) bool {
	if strings.HasSuffix(rel, "_test.go") || inTestSupport(rel) {
		return true
	}

	dir := path.Dir(rel)
	if inStore(dir) {
		return true
	}

	ok, _ := path.Match(queryPackagePattern, dir)

	return ok
}

// sqlLiteral returns the value of a string literal that reads as an SQL statement.
func sqlLiteral(n ast.Node) (string, bool) {
	lit, ok := n.(*ast.BasicLit)
	if !ok || lit.Kind != token.STRING {
		return "", false
	}

	value, err := strconv.Unquote(lit.Value)
	if err != nil || !sqlStatement.MatchString(value) {
		return "", false
	}

	return value, true
}

// sqlCall returns the method name of a call that runs SQL.
func sqlCall(n ast.Node) (string, bool) {
	call, ok := n.(*ast.CallExpr)
	if !ok {
		return "", false
	}

	sel, ok := call.Fun.(*ast.SelectorExpr)
	if !ok || !slices.Contains(sqlCallNames(), sel.Sel.Name) {
		return "", false
	}

	return sel.Sel.Name, true
}

// sqlUses returns "file:line: what" for every SQL statement literal and every call that
// runs SQL in the Go file rel.
func sqlUses(t *testing.T, rel string) []string {
	t.Helper()

	fset, file, ok := goSyntax(t, rel)
	if !ok {
		return nil
	}

	var found []string

	ast.Inspect(file, func(n ast.Node) bool {
		if n == nil {
			return false
		}

		line := fset.Position(n.Pos()).Line

		if value, isSQL := sqlLiteral(n); isSQL {
			first, _, _ := strings.Cut(strings.TrimSpace(value), "\n")
			found = append(found, fmt.Sprintf("%s:%d: SQL %q", rel, line, first))
		}

		if name, isCall := sqlCall(n); isCall {
			found = append(found, fmt.Sprintf("%s:%d: call to %s", rel, line, name))
		}

		return true
	})

	return found
}

