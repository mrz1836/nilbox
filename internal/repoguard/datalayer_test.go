// envValue returns the value that the env file rel assigns key, failing the test when it
// assigns none.
func envValue(t *testing.T, root, rel, key string) string {
	t.Helper()

	text, ok := readText(t, root, rel)
	require.True(t, ok, "%s is missing", rel)

	m := regexp.MustCompile(`(?m)^\s*` + regexp.QuoteMeta(key) + `=(\S+)`).FindStringSubmatch(text)
	require.NotNil(t, m, "%s no longer pins %s", rel, key)

	return m[1]
}

// sqlcOutput reports whether rel is a file sqlc generates into a query package.
func sqlcOutput(rel string) bool {
	dir, name := path.Split(rel)
	if ok, _ := path.Match(queryPackagePattern, path.Clean(dir)); !ok {
		return false
	}

	return strings.HasSuffix(name, ".sql.go") || name == "db.go" || name == "models.go"
}

func TestGeneratedSQLCVersion(t *testing.T) {
	t.Parallel()

	root := moduleRoot(t)
	want := envValue(t, root, projectEnvFile, sqlcVersionKey)

	var (
		checked int
		found   []string
	)

	for _, rel := range goFiles(t, root) {
		text, ok := readText(t, root, rel)
		if !ok || (!sqlcOutput(rel) && !strings.Contains(text, sqlcHeader)) {
			continue
		}

		checked++

		switch m := sqlcVersionLine.FindStringSubmatch(text); {
		case !strings.Contains(text, sqlcHeader):
			found = append(found, rel+": no sqlc header")
		case m == nil:
			found = append(found, rel+": names no sqlc version")
		case m[1] != want:
			found = append(found, rel+": sqlc "+m[1])
		}
	}

	require.NotZero(t, checked, "no generated queries found; update this guard")
	assert.Empty(t, found, "regenerate with magex db:generate, which runs the pinned sqlc %s", want)
}
