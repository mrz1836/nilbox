// The data layer is database/sql with typed queries that sqlc generates (sqlc.yaml). Each
// table has one owner package, which keeps its SQL in internal/<owner>/internal/queries;
// Go's internal rule then stops every other package from importing those queries.

const (
	// queryPackagePattern matches the directory of an owner's generated query package.
	queryPackagePattern = "internal/*/internal/queries"

	// storeDir holds the database plumbing (opening, migrations, transactions): the one
	// place outside the query packages that runs SQL of its own.
	storeDir = "internal/store"

	// migrationsDir holds the schema migrations, which sqlc also reads as the schema.
	migrationsDir = "internal/store/migrate/migrations"

	// projectEnvFile pins the sqlc version.
	projectEnvFile = ".github/env/90-project.env"

	// sqlcVersionKey names the sqlc pin in projectEnvFile.
	sqlcVersionKey = "SQLC_VERSION"

	// sqlcHeader starts every file sqlc generates. Built from parts so this file does not
	// match itself.
	sqlcHeader = "// Code generated by " + "sqlc. DO NOT EDIT."
)

// ormAllowlist lists the directories that still import the ORM while the data layer moves
// to database/sql and sqlc, one owner at a time. It only shrinks: TestNoORM fails on an
// entry with no ORM import left, so remove a directory once its last one is gone.
func ormAllowlist() []string {
	return []string{
		"internal/store",
		"internal/store/migrate",
		"internal/testutil",
	}
}

