// sqlTables returns, in order of first mention, the tables in owners that the SQL in text
// names. Any mention counts, not only the name after FROM, JOIN, INTO, or UPDATE, so a
// comma join, a subquery, or sqlc.embed cannot hide a table; comments, string literals,
// and parameter names are left out.
func sqlTables(text string, owners map[string]string) []string {
	text = sqlCommentOrString.ReplaceAllString(text, " ")
	text = sqlParameter.ReplaceAllString(text, " ")

	var tables []string

	for _, m := range sqlIdentifier.FindAllStringSubmatch(text, -1) {
		name := strings.ToLower(m[1] + m[2] + m[3] + m[4])
		if _, ok := owners[name]; ok && !slices.Contains(tables, name) {
			tables = append(tables, name)
		}
	}

	return tables
}

// liveTables returns the tables that the migrations, applied in order, leave in place.
func liveTables(migrations []string) map[string]bool {
	tables := map[string]bool{}

	for _, text := range migrations {
		text = sqlCommentOrString.ReplaceAllString(text, " ")

		for _, m := range tableChange.FindAllStringSubmatch(text, -1) {
			switch {
			case m[1] != "":
				tables[strings.ToLower(m[1])] = true
			case m[2] != "":
				delete(tables, strings.ToLower(m[2]))
			default:
				delete(tables, strings.ToLower(m[3]))
				tables[strings.ToLower(m[4])] = true
			}
		}
	}

	return tables
}

// repoTexts returns the text of every repository file that matches pattern, keyed by its
// path and in path order.
func repoTexts(t *testing.T, root, pattern string) ([]string, map[string]string) {
	t.Helper()

	texts := map[string]string{}

	for _, rel := range repoFiles(t, root) {
		if ok, _ := path.Match(pattern, rel); !ok {
			continue
		}

		if text, ok := readText(t, root, rel); ok {
			texts[rel] = text
		}
	}

	return slices.Sorted(maps.Keys(texts)), texts
}

// crossOwnerTables returns "file: table belongs to owner" for every table a query file
// touches that its package does not own.
func crossOwnerTables(files []string, texts, owners map[string]string) []string {
	var found []string

	for _, rel := range files {
		owner := strings.Split(rel, "/")[1]

		for _, table := range sqlTables(texts[rel], owners) {
			if owners[table] != owner {
				found = append(found, fmt.Sprintf("%s: %s belongs to %s", rel, table, owners[table]))
			}
		}
	}

	return found
}

// ownershipGaps returns, sorted, the live tables owners does not list and the tables it
// lists that are not live.
func ownershipGaps(live map[string]bool, owners map[string]string) ([]string, []string) {
	var unowned, gone []string

	for table := range live {
		if _, ok := owners[table]; !ok {
			unowned = append(unowned, table)
		}
	}

	for table := range owners {
		if !live[table] {
			gone = append(gone, table)
		}
	}

	slices.Sort(unowned)
	slices.Sort(gone)

	return unowned, gone
}

func TestQueryFilesTouchOwnTables(t *testing.T) {
	t.Parallel()

	root := moduleRoot(t)
	owners := tableOwners()

	t.Run("every query file touches only its package's tables", func(t *testing.T) {
		t.Parallel()

		files, texts := repoTexts(t, root, queryPackagePattern+"/*.sql")
		require.NotEmpty(t, files, "no query files found; update this guard")

		assert.Empty(t, crossOwnerTables(files, texts, owners),
			"only a table's owner queries it; others call the owner's API")
	})

	t.Run("every table the migrations create has one owner", func(t *testing.T) {
		t.Parallel()

		files, texts := repoTexts(t, root, migrationsDir+"/*.sql")
		require.NotEmpty(t, files, "no migrations found; update this guard")

		migrations := make([]string, 0, len(files))
		for _, rel := range files {
			migrations = append(migrations, texts[rel])
		}

		unowned, gone := ownershipGaps(liveTables(migrations), owners)
		assert.Empty(t, unowned, "add these tables, with their owner, to tableOwners")
		assert.Empty(t, gone, "no migration leaves these tables in place; remove them from tableOwners")
	})
}

func TestSQLTables(t *testing.T) {
	t.Parallel()

	owners := tableOwners()

	for name, tt := range map[string]struct {
		sql  string
		want []string
	}{
		"from and join": {
			sql:  "SELECT i.id FROM items i JOIN repos r ON r.id = i.repo_id",
			want: []string{"items", "repos"},
		},
		"comma join and subquery": {
			sql:  "SELECT 1 FROM items i, repos r WHERE i.account_id = (SELECT id FROM accounts)",
			want: []string{"items", "repos", "accounts"},
		},
		"insert, upsert, and case": {
			sql:  "INSERT INTO Prefs (key) VALUES (?) ON CONFLICT (key) DO UPDATE SET value = excluded.value",
			want: []string{"prefs"},
		},
		"quoted and embedded": {
			sql:  "SELECT sqlc.embed(\"prompts\") FROM [launch_defaults]",
			want: []string{"prompts", "launch_defaults"},
		},
		"comments, strings, and parameters are not tables": {
			sql: "-- reads the items' prefs\n/* notifications */ SELECT 'repos', sqlc.arg(accounts), @prompts " +
				"FROM claude_profiles WHERE name IN (sqlc.slice('items'))",
			want: []string{"claude_profiles"},
		},
		"a quote in a comment does not open a string": {
			sql:  "-- the item's state\nSELECT 1 FROM item_local_state",
			want: []string{"item_local_state"},
		},
		"unknown names are not tables": {
			sql:  "WITH recent AS (SELECT 1) SELECT * FROM recent, json_each(?)",
			want: nil,
		},
	} {
		assert.Equal(t, tt.want, sqlTables(tt.sql, owners), name)
	}
}

