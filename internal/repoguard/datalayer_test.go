// schemaChanges returns "where: name" for every schema change in the SQL text.
// Comments and string literals are left out.
func schemaChanges(where, text string) []string {
	matches := schemaChange.FindAllStringSubmatch(sqlCommentOrString.ReplaceAllString(text, " "), -1)
	found := make([]string, 0, len(matches))

	for _, m := range matches {
		found = append(found, where+": "+m[1])
	}

	return found
}

// literal is a string literal in a Go file: where it is, as "file:line", and its value.
type literal struct {
	where string
	value string
}

// stringLiterals returns every string literal in the Go file rel.
func stringLiterals(t *testing.T, rel string) []literal {
	t.Helper()

	fset, file, ok := goSyntax(t, rel)
	if !ok {
		return nil
	}

	var literals []literal

	ast.Inspect(file, func(n ast.Node) bool {
		lit, isLit := n.(*ast.BasicLit)
		if !isLit || lit.Kind != token.STRING {
			return true
		}

		if value, unquoteErr := strconv.Unquote(lit.Value); unquoteErr == nil {
			literals = append(literals, literal{fmt.Sprintf("%s:%d", rel, fset.Position(lit.Pos()).Line), value})
		}

		return true
	})

	return literals
}

// goSchemaChanges returns "file:line: name" for every schema change in a string literal of
// the Go file rel, except the migration runner creating its history table.
func goSchemaChanges(t *testing.T, rel string) []string {
	t.Helper()

	runner := path.Dir(rel) == migrateDir

	var found []string

	for _, lit := range stringLiterals(t, rel) {
		for _, change := range schemaChanges(lit.where, lit.value) {
			if !runner || !strings.HasSuffix(change, ": "+historyTable) {
				found = append(found, change)
			}
		}
	}

	return found
}

