package hooks

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"io"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
)

// hookHead caps how much of a hook is kept to read its text: its marker, and the lines
// that name another tool. The whole file is hashed.
const hookHead = 64 << 10

// The tools whose hooks the page names, as the plan's table and S3's recordings show
// them.
const (
	toolHusky     = "husky"
	toolPreCommit = "pre-commit"
	toolLefthook  = "lefthook"
)

// husky9Shim is how husky 9's hooks start the user's: they source h beside them, in
// .husky/_, the folder husky 9 sets core.hooksPath to.
var husky9Shim = regexp.MustCompile(`\$\(dirname (?:-- )?"\$0"\)/h"`)

// hookFile is one hook file as the scan read it.
type hookFile struct {
	// path is where it was read from.
	path string

	// present reports a file at path; err says why it couldn't be read.
	present bool
	err     error

	// ours reports go-pre-commit's marker in it, executable its executable bit, and sha
	// its contents' SHA-256, in hex.
	ours       bool
	executable bool
	sha        string

	// tool names another tool's hook where its text tells: husky, pre-commit, or
	// lefthook; "" for go-pre-commit's own, or one it can't name.
	tool string
}

// readHook reads the hook at path, following a link as git does.
func readHook(path string) hookFile {
	info, err := os.Stat(path)

	switch {
	case errors.Is(err, fs.ErrNotExist):
		return hookFile{path: path}
	case err != nil:
		return hookFile{path: path, present: true, err: err}
	case !info.Mode().IsRegular():
		return hookFile{path: path, present: true, err: errNotAFile}
	}

	f, err := os.Open(path) //nolint:gosec // a hook in a clone's hooks folder, only read
	if err != nil {
		return hookFile{path: path, present: true, err: err}
	}

	defer func() { _ = f.Close() }()

	sum := sha256.New()
	head := &capped{limit: hookHead}

	if _, err = io.Copy(io.MultiWriter(sum, head), f); err != nil {
		return hookFile{path: path, present: true, err: err}
	}

	text := head.buf.String()
	out := hookFile{
		path: path, present: true, ours: strings.Contains(text, marker), executable: info.Mode()&0o111 != 0,
		sha: hex.EncodeToString(sum.Sum(nil)),
	}

	if !out.ours {
		out.tool = otherTool(text, filepath.Dir(path))
	}

	return out
}

// otherTool names the tool whose hook text is, in the folder dir, or returns "".
func otherTool(text, dir string) string {
	lower := strings.ToLower(text)

	switch {
	case strings.Contains(lower, toolLefthook):
		return toolLefthook
	case strings.Contains(lower, "file generated by pre-commit") || strings.Contains(lower, "pre-commit.com"):
		return toolPreCommit
	case strings.Contains(lower, toolHusky) || husky9Shim.MatchString(text):
		return toolHusky
	case strings.Contains(filepath.ToSlash(dir), "/.husky/"):
		return toolHusky
	default:
		return ""
	}
}

// markedTypes returns the hook types in the folder hooks that carry go-pre-commit's
// marker, in hookTypes' order.
func markedTypes(hooks string) []string {
	out := []string{}

	for _, t := range hookTypes() {
		if h := readHook(filepath.Join(hooks, t)); h.ours {
			out = append(out, t)
		}
	}

	return out
}

// backups returns the names of the pre-commit hooks go-pre-commit set aside in the folder
// hooks, sorted as go-pre-commit sorts them when it puts the last one back.
func backups(hooks string) []string {
	entries, err := os.ReadDir(hooks)
	if err != nil {
		return []string{}
	}

	out := []string{}

	for _, e := range entries {
		if strings.HasPrefix(e.Name(), backupPrefix) && !e.IsDir() {
			out = append(out, e.Name())
		}
	}

	slices.Sort(out)

	return out
}

// capped keeps the first limit bytes written to it, and takes the rest without keeping
// it.
type capped struct {
	buf   bytes.Buffer
	limit int
}

// Write keeps what fits under the limit. It never fails.
func (c *capped) Write(p []byte) (int, error) {
	if room := c.limit - c.buf.Len(); room > 0 {
		c.buf.Write(p[:min(room, len(p))])
	}

	return len(p), nil
}
