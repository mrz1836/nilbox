func TestReadHook(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	writeFile(t, dir, "ours", currentHook, 0o755)
	writeFile(t, dir, "off", currentHook, 0o644)
	writeFile(t, dir, "husky", huskyHook, 0o755)
	require.NoError(t, os.MkdirAll(filepath.Join(dir, "folder"), 0o700))
	require.NoError(t, os.Symlink(filepath.Join(dir, "ours"), filepath.Join(dir, "link")))

	sum := sha256.Sum256([]byte(currentHook))
	want := hex.EncodeToString(sum[:])

	ours := readHook(filepath.Join(dir, "ours"))
	assert.Equal(t, hookFile{
		path: filepath.Join(dir, "ours"), present: true, ours: true, executable: true, sha: want,
	}, ours)

	off := readHook(filepath.Join(dir, "off"))
	assert.True(t, off.ours)
	assert.False(t, off.executable)

	husky := readHook(filepath.Join(dir, "husky"))
	assert.False(t, husky.ours)
	assert.Equal(t, toolHusky, husky.tool)

	link := readHook(filepath.Join(dir, "link"))
	assert.Equal(t, want, link.sha, "a link is followed, as git does")

	missing := readHook(filepath.Join(dir, "missing"))
	assert.False(t, missing.present)
	require.NoError(t, missing.err)

	folder := readHook(filepath.Join(dir, "folder"))
	assert.True(t, folder.present)
	require.ErrorIs(t, folder.err, errNotAFile)
}

func TestReadHookHashesAWholeLongFile(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	long := strings.Repeat("echo padding\n", hookHead/8) + "# " + marker + "\n"
	writeFile(t, dir, "long", long, 0o755)

	got := readHook(filepath.Join(dir, "long"))
	sum := sha256.Sum256([]byte(long))

	assert.Equal(t, hex.EncodeToString(sum[:]), got.sha)
	assert.False(t, got.ours, "only the start of a hook is read for its marker")
}

func TestOtherTool(t *testing.T) {
	t.Parallel()

	for _, c := range []struct {
		text, dir, want string
	}{
		{huskyHook, "/srv/clone/.git/hooks", toolHusky},
		{"#!/usr/bin/env sh\n. \"$(dirname \"$0\")/h\"\n", "/srv/clone/.git/hooks", toolHusky},
		{"#!/bin/sh\necho hi\n", "/srv/clone/.husky/_", toolHusky},
		{"#!/usr/bin/env bash\n# File generated by pre-commit: https://pre-commit.com\n", "/srv/clone/.git/hooks", toolPreCommit},
		{"#!/bin/sh\ncall_lefthook run \"pre-commit\" \"$@\"\n", "/srv/clone/.git/hooks", toolLefthook},
		{"#!/bin/sh\nif [ \"$LEFTHOOK\" = \"0\" ]; then exit 0; fi\n", "/srv/clone/.git/hooks", toolLefthook},
		{"#!/bin/sh\nmake lint\n", "/srv/clone/.git/hooks", ""},
	} {
		assert.Equal(t, c.want, otherTool(c.text, c.dir), "%q in %s", c.text, c.dir)
	}
}

func TestMarkedTypesAndBackups(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	writeFile(t, dir, "pre-commit", currentHook, 0o755)
	writeFile(t, dir, hookCommitMsg, oldHook, 0o755)
	writeFile(t, dir, "pre-push", "#!/bin/sh\nexit 0\n", 0o755)
	writeFile(t, dir, "pre-commit.backup.9", huskyHook, 0o700)
	writeFile(t, dir, "pre-commit.backup.10", huskyHook, 0o700)
	writeFile(t, dir, "pre-commit.sample", "#!/bin/sh\n", 0o755)

	assert.Equal(t, []string{"pre-commit", hookCommitMsg}, markedTypes(dir))
	assert.Equal(t, []string{"pre-commit.backup.10", "pre-commit.backup.9"}, backups(dir), "sorted as go-pre-commit sorts")

	empty := filepath.Join(dir, "missing")
	assert.Empty(t, markedTypes(empty))
	assert.NotNil(t, backups(empty))
	assert.Empty(t, backups(empty))
}
