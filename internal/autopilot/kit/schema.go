		strconv.Itoa(catalog.MaxRunTokens) + " tokens; a routine's daily budget $" + dollarWords(catalog.MinDayCents) +
		" to $" + dollarWords(catalog.MaxDayCents) + " or " + strconv.Itoa(catalog.MinDayTokens) + " to " +
		strconv.Itoa(catalog.MaxDayTokens) + " tokens. Dollars go to the cent."
