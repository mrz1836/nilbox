// limitAt names the key of the struct type T a limit is laid on.
func limitAt[T any](key string) schemaAt {
	return schemaAt{owner: reflect.TypeFor[T](), key: key}
}

// limitSpan is a whole number's range, both ends included.
func limitSpan(low, high int) schemaNode {
	return schemaNode{Minimum: new(low), Maximum: new(high)}
}
