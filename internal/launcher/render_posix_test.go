// fakeAgent is a stand-in for the agent binary. It prints its working directory, two
// environment variables, and then every argument, each terminated by a NUL byte, so the
// test can check argument boundaries exactly.
const fakeAgent = `#!/bin/sh
printf 'cwd=%s\000' "$(pwd -P)"
printf 'cfg=%s\000' "${CLAUDE_CONFIG_DIR-<unset>}"
printf 'extra=%s\000' "${EXTRA_VAR-<unset>}"
for a in "$@"; do printf '%s\000' "$a"; done
`

// runSh runs a shell command line with /bin/sh and returns its stdout.
func runSh(t *testing.T, env []string, args ...string) ([]byte, error) {
	t.Helper()

	cmd := exec.CommandContext(t.Context(), "/bin/sh", args...) //nolint:gosec // runs the test's own generated script
	cmd.Env = env

	var stderr bytes.Buffer

	cmd.Stderr = &stderr

	out, err := cmd.Output()
	if err != nil {
		t.Logf("sh stderr: %s", stderr.String())
	}

	return out, err
}

// writeExecutable writes an executable file for the test.
func writeExecutable(t *testing.T, path, body string) {
	t.Helper()

	require.NoError(t, os.WriteFile(path, []byte(body), 0o700)) //nolint:gosec // test executable must be runnable
}

func TestShellQuote(t *testing.T) {
	tests := []struct {
		name  string
		input string
		want  string
	}{
		{name: "plain", input: "plain", want: "'plain'"},
		{name: "empty", input: "", want: "''"},
		{name: "spaces", input: "two words  here", want: "'two words  here'"},
		{name: "single quote", input: "it's", want: `'it'\''s'`},
		{name: "only quotes", input: "''", want: `''\'''\'''`},
		{name: "double quote", input: `say "hi"`, want: `'say "hi"'`},
		{name: "dollar", input: "$HOME and ${USER}", want: "'$HOME and ${USER}'"},
		{name: "command substitution", input: "$(id) `whoami`", want: "'$(id) `whoami`'"},
		{name: "newline", input: "line one\nline two", want: "'line one\nline two'"},
		{name: "unicode", input: "café naïve 🚀", want: "'café naïve 🚀'"},
		{name: "leading hash", input: "#7", want: "'#7'"},
		{name: "backslash", input: `C:\path\n`, want: `'C:\path\n'`},
		{name: "shell operators", input: "a; b && c | d > e < f &", want: "'a; b && c | d > e < f &'"},
		{name: "globs and tilde", input: "~/x/*.go [ab]?", want: "'~/x/*.go [ab]?'"},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := shQuote(tt.input)
			assert.Equal(t, tt.want, got)

			out, err := runSh(t, os.Environ(), "-c", "printf %s "+got)
			require.NoError(t, err)
			assert.Equal(t, tt.input, string(out), "the shell reads back exactly the input")
		})
	}
}

// goldenPlan is a plan with every part the renderer writes.
func goldenPlan() Plan {
	return Plan{
		Kind:       KindPR,
		Number:     7,
		Dir:        "/tmp/projects/example repo",
		Binary:     "/tmp/bin/claude",
		Args:       []string{"--model", "opus", "--permission-mode", "plan", "--add-dir=/tmp/it's here", "--worktree", "#7"},
		Env:        map[string]string{"ZED": "last", "CLAUDE_CONFIG_DIR": "/tmp/home/.claude_work", "A_VAR": "$HOME"},
		Unset:      []string{"OLD_VAR"},
		PromptFile: "/tmp/launch/pr-7.prompt.md",
	}
}

func TestRenderScript(t *testing.T) {
	want := "#!/bin/sh\n" +
		"# Generated by " + brand.Name + " to start a coding session. Safe to delete.\n" +
		"set -eu\n" +
		"cd -- '/tmp/projects/example repo' || exit 1\n" +
		"unset OLD_VAR\n" +
		"export A_VAR='$HOME'\n" +
		"export CLAUDE_CONFIG_DIR='/tmp/home/.claude_work'\n" +
		"export ZED='last'\n" +
		"prompt=$(cat -- '/tmp/launch/pr-7.prompt.md')\n" +
		`exec '/tmp/bin/claude' "$prompt" '--model' 'opus' '--permission-mode' 'plan' ` +
		`'--add-dir=/tmp/it'\''s here' '--worktree' '#7'` + "\n"

	got := POSIXRenderer{}.Render(goldenPlan())
	assert.Equal(t, want, string(got))

	path := filepath.Join(t.TempDir(), "golden.command")
	require.NoError(t, os.WriteFile(path, got, 0o600))

	_, err := runSh(t, os.Environ(), "-n", path)
	require.NoError(t, err, "the script parses")

	t.Run("no args, no env", func(t *testing.T) {
		plan := Plan{Dir: "/tmp/d", Binary: "/tmp/claude", PromptFile: "/tmp/p"}
		assert.Equal(t, "#!/bin/sh\n"+
			"# Generated by "+brand.Name+" to start a coding session. Safe to delete.\n"+
			"set -eu\n"+
			"cd -- '/tmp/d' || exit 1\n"+
			"prompt=$(cat -- '/tmp/p')\n"+
			`exec '/tmp/claude' "$prompt"`+"\n", string(POSIXRenderer{}.Render(plan)))
	})

	assert.Equal(t, ".command", DefaultRenderer().Extension())
}

func TestPromptNeverOnCommandLine(t *testing.T) {
	prompt := "Review pull request #7: it's `rm -rf ~` $(curl evil) \"quoted\"\nsecond line"

	req := baseRequest()
	req.Worktree = true

	plan, err := BuildPlan(req)
	require.NoError(t, err)

	files, err := WriteLaunchFiles(testPaths(t), plan, prompt, fixedNow())
	require.NoError(t, err)

	script, err := os.ReadFile(files.Script)
	require.NoError(t, err)

	for _, piece := range []string{prompt, "Review pull request", "rm -rf", "curl evil", "second line"} {
		assert.NotContains(t, string(script), piece)
	}

	assert.Contains(t, string(script), "prompt=$(cat -- "+shQuote(files.Prompt)+")\n")
	assert.Contains(t, string(script), `"$prompt"`)

	stored, err := os.ReadFile(files.Prompt)
	require.NoError(t, err)
	assert.Equal(t, prompt, string(stored))
}

func TestRenderedScriptRunsWithExactArgv(t *testing.T) {
	root := t.TempDir()
	clone := filepath.Join(root, "clone dir 'quoted' $x")
	require.NoError(t, os.MkdirAll(clone, 0o700))

	agent := filepath.Join(root, "bin with space", "claude")
	require.NoError(t, os.MkdirAll(filepath.Dir(agent), 0o700))
	writeExecutable(t, agent, fakeAgent)

	req := baseRequest()
	req.Clone.Dir = clone
	req.ClaudePath = agent
	req.Worktree = true
	req.Profile.AddDirs = []string{filepath.Join(root, "docs; rm -rf x")}
	req.Profile.ExtraArgs = []string{"--append-system-prompt", "keep `this` & $that", "--verbose"}
	req.Profile.Env = map[string]string{"EXTRA_VAR": "it's $HOME\nnext"}

	plan, err := BuildPlan(req)
	require.NoError(t, err)

	prompt := "Review #7: it's `id` $(id) \"q\"\n\nwith café 🚀\n"

	files, err := WriteLaunchFiles(testPaths(t), plan, prompt, fixedNow())
	require.NoError(t, err)

	env := append(os.Environ(), "CLAUDE_CONFIG_DIR="+filepath.Join(root, "inherited"))

	out, err := runSh(t, env, files.Script)
	require.NoError(t, err)

	realClone, err := filepath.EvalSymlinks(clone)
	require.NoError(t, err)

	fields := strings.Split(strings.TrimSuffix(string(out), "\x00"), "\x00")
	require.GreaterOrEqual(t, len(fields), 3)
	assert.Equal(t, "cwd="+realClone, fields[0])
	assert.Equal(t, "cfg=<unset>", fields[1], "the default profile unsets an inherited config dir")
	assert.Equal(t, "extra=it's $HOME\nnext", fields[2])

	// $(...) drops the prompt's trailing newlines; everything else arrives intact, as one
	// argument, in front of every flag.
	wantArgv := plan.Argv(strings.TrimRight(prompt, "\n"))[1:]
	assert.Equal(t, wantArgv, fields[3:])
	assert.Equal(t, []string{"--worktree", "#7"}, fields[len(fields)-2:])
}

func TestRenderedScriptStopsWhenTheCloneIsMissing(t *testing.T) {
	root := t.TempDir()
	marker := filepath.Join(root, "agent-ran")
	agent := filepath.Join(root, "claude")
	writeExecutable(t, agent, "#!/bin/sh\ntouch "+shQuote(marker)+"\n")

	req := baseRequest()
	req.Clone.Dir = filepath.Join(root, "gone")
	req.ClaudePath = agent

	plan, err := BuildPlan(req)
	require.NoError(t, err)

	files, err := WriteLaunchFiles(testPaths(t), plan, "Review", fixedNow())
	require.NoError(t, err)

	_, err = runSh(t, os.Environ(), files.Script)
	require.Error(t, err)
	assert.NoFileExists(t, marker)
}

func TestRenderQuotesInvalidEnvNames(t *testing.T) {
	root := t.TempDir()
	marker := filepath.Join(root, "injected")

	// BuildPlan never produces such names; the renderer still never runs them.
	plan := Plan{
		Dir:        root,
		Binary:     filepath.Join(root, "missing-agent"),
		Env:        map[string]string{"A;touch " + marker + ";B": "v"},
		Unset:      []string{"C$(touch " + marker + ")"},
		PromptFile: filepath.Join(root, "missing-prompt"),
	}

	script := string(POSIXRenderer{}.Render(plan))
	assert.Contains(t, script, "unset "+shQuote(plan.Unset[0])+"\n")
	assert.Contains(t, script, "export "+shQuote("A;touch "+marker+";B")+"='v'\n")

	path := filepath.Join(root, "bad.command")
	require.NoError(t, os.WriteFile(path, []byte(script), 0o600))

	_, err := runSh(t, os.Environ(), path)
	require.Error(t, err, "the shell rejects the invalid name and stops")
	assert.NoFileExists(t, marker)
}
