// runSh runs a shell command line with /bin/sh and returns its stdout.
func runSh(t *testing.T, env []string, args ...string) ([]byte, error) {
	t.Helper()

	cmd := exec.CommandContext(t.Context(), "/bin/sh", args...) //nolint:gosec // runs the test's own generated script
	cmd.Env = env

	var stderr bytes.Buffer

	cmd.Stderr = &stderr

	out, err := cmd.Output()
	if err != nil {
		t.Logf("sh stderr: %s", stderr.String())
	}

	return out, err
}

func TestShellQuote(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name  string
		input string
		want  string
	}{
		{name: "plain", input: "plain", want: "'plain'"},
		{name: "empty", input: "", want: "''"},
		{name: "spaces", input: "two words  here", want: "'two words  here'"},
		{name: "single quote", input: "it's", want: `'it'\''s'`},
		{name: "only quotes", input: "''", want: `''\'''\'''`},
		{name: "double quote", input: `say "hi"`, want: `'say "hi"'`},
		{name: "dollar", input: "$HOME and ${USER}", want: "'$HOME and ${USER}'"},
		{name: "command substitution", input: "$(id) `whoami`", want: "'$(id) `whoami`'"},
		{name: "newline", input: "line one\nline two", want: "'line one\nline two'"},
		{name: "unicode", input: "café naïve 🚀", want: "'café naïve 🚀'"},
		{name: "leading hash", input: "#7", want: "'#7'"},
		{name: "backslash", input: `C:\path\n`, want: `'C:\path\n'`},
		{name: "shell operators", input: "a; b && c | d > e < f &", want: "'a; b && c | d > e < f &'"},
		{name: "globs and tilde", input: "~/x/*.go [ab]?", want: "'~/x/*.go [ab]?'"},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			got := shQuote(tt.input)
			assert.Equal(t, tt.want, got)

			out, err := runSh(t, os.Environ(), "-c", "printf %s "+got)
			require.NoError(t, err)
			assert.Equal(t, tt.input, string(out), "the shell reads back exactly the input")
		})
	}
}

// goldenScript is a script with every part the renderer writes.
func goldenScript() Script {
	return Script{
		Dir:        "/tmp/projects/example repo",
		Binary:     "/tmp/bin/claude",
		Args:       []string{"--model", "opus", "--permission-mode", "plan", "--add-dir=/tmp/it's here", "--worktree", "#7"},
		Env:        map[string]string{"ZED": "last", "CLAUDE_CONFIG_DIR": "/tmp/home/.claude_work", "A_VAR": "$HOME"},
		Unset:      []string{"OLD_VAR"},
		PromptFile: "/tmp/launch/pr-7.prompt.md",
	}
}

func TestRenderScript(t *testing.T) {
	t.Parallel()

	want := "#!/bin/sh\n" +
		"# Generated by " + brand.Name + " to start a coding session. Safe to delete.\n" +
		"set -eu\n" +
		"cd -- '/tmp/projects/example repo' || exit 1\n" +
		"unset OLD_VAR\n" +
		"export A_VAR='$HOME'\n" +
		"export CLAUDE_CONFIG_DIR='/tmp/home/.claude_work'\n" +
		"export ZED='last'\n" +
		"prompt=$(cat -- '/tmp/launch/pr-7.prompt.md')\n" +
		`exec '/tmp/bin/claude' "$prompt" '--model' 'opus' '--permission-mode' 'plan' ` +
		`'--add-dir=/tmp/it'\''s here' '--worktree' '#7'` + "\n"

	got := POSIXRenderer{}.Render(goldenScript())
	assert.Equal(t, want, string(got))

	path := filepath.Join(t.TempDir(), "golden.command")
	require.NoError(t, os.WriteFile(path, got, 0o600))

	_, err := runSh(t, os.Environ(), "-n", path)
	require.NoError(t, err, "the script parses")

	t.Run("no args, no env", func(t *testing.T) {
		t.Parallel()

		script := Script{Dir: "/tmp/d", Binary: "/tmp/claude", PromptFile: "/tmp/p"}
		assert.Equal(t, "#!/bin/sh\n"+
			"# Generated by "+brand.Name+" to start a coding session. Safe to delete.\n"+
			"set -eu\n"+
			"cd -- '/tmp/d' || exit 1\n"+
			"prompt=$(cat -- '/tmp/p')\n"+
			`exec '/tmp/claude' "$prompt"`+"\n", string(POSIXRenderer{}.Render(script)))
	})

	t.Run("prompt last", func(t *testing.T) {
		t.Parallel()

		script := Script{
			Dir: "/tmp/d", Binary: "/tmp/codex", PromptFile: "/tmp/p", Args: []string{"--sandbox", "read-only", "--"},
			Env: map[string]string{"CODEX_HOME": "/tmp/home/.codex_work"}, PromptLast: true,
		}
		assert.Equal(t, "#!/bin/sh\n"+
			"# Generated by "+brand.Name+" to start a coding session. Safe to delete.\n"+
			"set -eu\n"+
			"cd -- '/tmp/d' || exit 1\n"+
			"export CODEX_HOME='/tmp/home/.codex_work'\n"+
			"prompt=$(cat -- '/tmp/p')\n"+
			`exec '/tmp/codex' '--sandbox' 'read-only' '--' "$prompt"`+"\n", string(POSIXRenderer{}.Render(script)))
	})

	t.Run("no prompt", func(t *testing.T) {
		t.Parallel()

		script := Script{
			Dir: "/tmp/d", Binary: "/tmp/codex", PromptFile: "/tmp/p", Args: []string{"resume", "--", "abc"},
			PromptLast: true, NoPrompt: true,
		}
		got := POSIXRenderer{}.Render(script)
		assert.Equal(t, "#!/bin/sh\n"+
			"# Generated by "+brand.Name+" to start a coding session. Safe to delete.\n"+
			"set -eu\n"+
			"cd -- '/tmp/d' || exit 1\n"+
			`exec '/tmp/codex' 'resume' '--' 'abc'`+"\n", string(got), "a resumed session reads no prompt file")

		path := filepath.Join(t.TempDir(), "resume.command")
		require.NoError(t, os.WriteFile(path, got, 0o600))

		_, err := runSh(t, os.Environ(), "-n", path)
		require.NoError(t, err, "the script parses")
	})

	assert.Equal(t, ".command", DefaultRenderer().Extension())
}

func TestRenderQuotesInvalidEnvNames(t *testing.T) {
	t.Parallel()

	root := t.TempDir()
	marker := filepath.Join(root, "injected")

	// A launch plan never holds such names; the renderer still never runs them.
	bad := Script{
		Dir:        root,
		Binary:     filepath.Join(root, "missing-agent"),
		Env:        map[string]string{"A;touch " + marker + ";B": "v"},
		Unset:      []string{"C$(touch " + marker + ")"},
		PromptFile: filepath.Join(root, "missing-prompt"),
	}

	script := string(POSIXRenderer{}.Render(bad))
	assert.Contains(t, script, "unset "+shQuote(bad.Unset[0])+"\n")
	assert.Contains(t, script, "export "+shQuote("A;touch "+marker+";B")+"='v'\n")

	path := filepath.Join(root, "bad.command")
	require.NoError(t, os.WriteFile(path, []byte(script), 0o600))

	_, err := runSh(t, os.Environ(), path)
	require.Error(t, err, "the shell rejects the invalid name and stops")
	assert.NoFileExists(t, marker)
}

func TestValidEnvName(t *testing.T) {
	t.Parallel()

	for name, want := range map[string]bool{
		"CLAUDE_CONFIG_DIR": true,
		"_private":          true,
		"a1":                true,
		"":                  false,
		"1A":                false,
		"A-B":               false,
		"A B":               false,
		"A;B":               false,
		"A=B":               false,
		"$(id)":             false,
		"CAFÉ":              false,
	} {
		assert.Equal(t, want, ValidEnvName(name), name)
	}
}
