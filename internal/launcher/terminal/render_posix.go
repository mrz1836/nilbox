package terminal

import (
	"maps"
	"regexp"
	"slices"
	"strings"

	"github.com/mrz1836/nilbox/internal/brand"
)

// envNamePattern is what an environment variable name must look like.
var envNamePattern = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)

// Script is what a launch script does: it changes into Dir, unsets the variables in
// Unset, sets those in Env, reads the prompt from PromptFile, and replaces itself with
// Binary, passing the prompt first and then Args.
type Script struct {
	// Dir is the directory the session starts in.
	Dir string

	// Binary is the agent binary's absolute path.
	Binary string

	// Args are the arguments that follow the prompt, one argv element each.
	Args []string

	// Env holds the environment variables to set.
	Env map[string]string

	// Unset lists environment variables to remove.
	Unset []string

	// PromptFile holds the prompt text the script passes as the first argument.
	PromptFile string
}

// ScriptRenderer writes a Script as a file a terminal can run. A port to another shell
// family adds a renderer; callers never build command lines themselves.
type ScriptRenderer interface {
	// Render returns the script file's contents for s. The script reads the prompt from
	// s.PromptFile when it runs.
	Render(s Script) []byte

	// Extension is the script file's extension, including the dot.
	Extension() string
}

// ValidEnvName reports whether name can name an environment variable: a letter or an
// underscore, then letters, digits, and underscores.
func ValidEnvName(name string) bool {
	return envNamePattern.MatchString(name)
}

// POSIXRenderer renders scripts as POSIX sh. Every value is single-quoted, so no
// path, argument, or environment value is ever interpreted by the shell, and the prompt
// is read from its file rather than written into the script.
type POSIXRenderer struct{}

// DefaultRenderer returns the script renderer for launch files.
func DefaultRenderer() ScriptRenderer {
	return POSIXRenderer{}
}

// Extension returns ".command", which macOS terminals open and run directly.
func (POSIXRenderer) Extension() string { return ".command" }

// Render returns a script that changes into s.Dir, adjusts the environment, reads the
// prompt file, and replaces itself with the agent:
//
//	#!/bin/sh
//	set -eu
//	cd -- '<dir>' || exit 1
//	unset NAME
//	export NAME='value'
//	prompt=$(cat -- '<prompt file>')
//	exec '<agent>' "$prompt" '<arg>' ...
func (POSIXRenderer) Render(s Script) []byte {
	var b strings.Builder

	b.WriteString("#!/bin/sh\n")
	b.WriteString("# Generated by " + brand.Name + " to start a coding session. Safe to delete.\n")
	b.WriteString("set -eu\n")
	b.WriteString("cd -- " + shQuote(s.Dir) + " || exit 1\n")

	for _, name := range s.Unset {
		b.WriteString("unset " + shName(name) + "\n")
	}

	for _, name := range slices.Sorted(maps.Keys(s.Env)) {
		b.WriteString("export " + shName(name) + "=" + shQuote(s.Env[name]) + "\n")
	}

	b.WriteString("prompt=$(cat -- " + shQuote(s.PromptFile) + ")\n")
	b.WriteString("exec " + shQuote(s.Binary) + ` "$prompt"`)

	for _, arg := range s.Args {
		b.WriteString(" " + shQuote(arg))
	}

	b.WriteString("\n")

	return []byte(b.String())
}

// shName returns an environment variable name as the script writes it. A valid name is
// written as is. Anything else (which a launch plan never holds) is quoted, so the shell
// rejects it as an invalid identifier and the script stops instead of running it.
func shName(name string) string {
	if ValidEnvName(name) {
		return name
	}

	return shQuote(name)
}

// shQuote quotes s for a POSIX shell. It is wrapped in single quotes, inside which
// nothing is special, and each single quote inside it closes the quoting, adds an
// escaped quote, and reopens the quoting.
func shQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}
